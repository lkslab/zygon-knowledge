# -*- coding: utf-8 -*-
"""
Regenerates the methods book's three index files from the cards.

  INDEX.md       the retrieval surface: per family, one row per method with both
                 models' verdict and entry rung. This is what an agent scans.
  PREVALENCE.md  what this literature actually does, ranked by paper count — the
                 answer to "which methods matter", backed by the corpus.
  PRIMITIVES.md  methods where the PyPSA library has the primitive but neither
                 workflow exposes it. A product artifact, not an index: it is the
                 ranked list of capabilities that are one wrapper away.

Mirrors cookbooks/pypsa-eur/demand/_qa/generate_index.py (FAMILIES grouping, an
`Unindexed` catch-all so a new card can never be silently dropped from the index).

Usage:  python cookbooks/methods/_qa/generate_index.py
"""

import os
import sys

import yaml

QA_DIR = os.path.dirname(os.path.abspath(__file__))
BOOK_DIR = os.path.dirname(QA_DIR)

# entry rung = the cheapest rung on a model's ladder; what the interview quotes first
RUNG_ORDER = ["L0", "L1", "L2", "L3", "L4", "L5"]
VERDICT_MARK = {
    "turnkey": "turnkey",
    "assemble": "assemble",
    "primitive-only": "primitive",
    "absent": "absent",
}


def load(path):
    with open(path) as f:
        return yaml.safe_load(f)


def entry_rung(msec):
    rungs = [b.get("rung") for b in (msec.get("boundary") or []) if b.get("rung") in RUNG_ORDER]
    return min(rungs, key=RUNG_ORDER.index) if rungs else "--"


def model_cell(card, model):
    for m in card.get("models") or []:
        if m.get("model") == model:
            if m.get("not_applicable"):
                return "n/a", "--"
            v = VERDICT_MARK.get((m.get("available") or {}).get("verdict"), "?")
            return v, entry_rung(m)
    return "--", "--"


def main():
    slugdoc = load(os.path.join(QA_DIR, "SLUGS.yaml"))
    families = slugdoc["families"]
    corpus_path = os.path.join(QA_DIR, "CORPUS.yaml")
    n_papers = len(load(corpus_path)) if os.path.isfile(corpus_path) else "?"

    cards = {}
    # v1 essays live in v1/ pending conversion; flat entries are v2
    entries = [(f, f) for f in sorted(os.listdir(BOOK_DIR))]
    v1_dir = os.path.join(BOOK_DIR, "v1")
    if os.path.isdir(v1_dir):
        entries += [(os.path.join("v1", f), f"v1/{f}")
                    for f in sorted(os.listdir(v1_dir))]
    for fname, link in entries:
        if os.path.basename(fname) == "TEMPLATE.yaml" or fname == "v1":
            continue
        path = os.path.join(BOOK_DIR, fname)
        # dir-form method (<slug>/spec.yaml) carries payload assets
        if os.path.isdir(path):
            path = os.path.join(path, "spec.yaml")
            if not os.path.isfile(path):
                continue
            link = f"{fname}/spec.yaml"
        elif not fname.endswith(".yaml"):
            continue
        doc = load(path)
        if isinstance(doc, dict) and doc.get("id"):
            doc["_link"] = link
            cards[doc["id"]] = doc
    if not cards:
        print("no method cards found — nothing to index")
        sys.exit(0)

    # ── INDEX.md ────────────────────────────────────────────────────────────
    L = [
        "# Methods book — index",
        "",
        "GENERATED by `_qa/generate_index.py` — do not edit.",
        "",
        f"{len(cards)} methods, extracted from the {n_papers}-paper corpus in `papers/`.",
        "Organised by *method* (how something is modelled), where `topics/` is organised by",
        "*question* and `generation_conversion/`+`demand/` by *thing*.",
        "",
        "**Read `when_to_use` to route, then open ONE card.** Never browse this book.",
        "",
        "Columns: `verdict` is what the workflow can execute — `turnkey` (a config flip runs",
        "it) / `assemble` (all surfaces exist, you wire them) / `primitive` (PyPSA has it, the",
        "workflow does not expose it) / `absent` (neither layer has it). `rung` is the CHEAPEST",
        "rung on that model's ladder; the card's `boundary` has the rung per variant.",
        "",
    ]
    seen = set()
    for fam, blurb in families.items():
        members = sorted([c for c in cards.values() if c.get("family") == fam],
                         key=lambda c: -(c.get("prevalence", {}).get("papers") or 0))
        if not members:
            continue
        L += [f"## {fam}", "", f"*{blurb.strip()}*", "",
              "| method | papers | eur | rung | earth | rung | pypsa primitive |",
              "|---|---:|---|---|---|---|---|"]
        for c in members:
            seen.add(c["id"])
            ev, er = model_cell(c, "pypsa-eur")
            av, ar = model_cell(c, "pypsa-earth")
            prim = c.get("pypsa_primitive")
            pcell = "--"
            if prim:
                sym = str(prim.get("symbol", "")).split(":")[-1]
                exp = str(prim.get("exposed_by", ""))
                pcell = f"`{sym}`" + (" **(unexposed)**" if exp.strip().startswith("neither") else "")
            L.append(f"| [{c['title']}]({c.get('_link', c['id'] + '.yaml')}) | "
                     f"{c.get('prevalence', {}).get('papers', '?')} | {ev} | {er} | "
                     f"{av} | {ar} | {pcell} |")
        L.append("")
    unindexed = [c for c in cards.values() if c["id"] not in seen]
    if unindexed:
        L += ["## Unindexed", "",
              "Cards whose `family` is not in `_qa/SLUGS.yaml:families` — fix one or the other.", ""]
        L += [f"- [{c['id']}]({c.get('_link', c['id'] + '.yaml')}) "
              f"(family: {c.get('family')!r})" for c in unindexed]
        L.append("")
    with open(os.path.join(BOOK_DIR, "INDEX.md"), "w") as f:
        f.write("\n".join(L))

    # ── PREVALENCE.md ───────────────────────────────────────────────────────
    ranked = sorted(cards.values(),
                    key=lambda c: -(c.get("prevalence", {}).get("papers") or 0))
    P = [
        "# What this literature actually does",
        "",
        "GENERATED by `_qa/generate_index.py` — do not edit.",
        "",
        "Methods ranked by how many of the 100 corpus papers use them, from the hand-coded",
        "pass over every paper. `sweep` is what the regex screen in `_qa/SWEEP.csv` found;",
        "the two disagree often and each card's `prevalence.basis` explains its own gap.",
        "Roles: `def`ines / `ext`ends / `can`onical-use / `rou`tine-use / `cri`tiques.",
        "",
        "A high `rou` count is the honest reading of a field-wide default — a method 40 papers",
        "use routinely is one whose assumptions most authors inherited without examining.",
        "",
        "| method | papers | t1 | t2 | sweep | def | ext | can | rou | cri |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for c in ranked:
        pv = c.get("prevalence", {})
        roles = {}
        for l in c.get("literature") or []:
            roles[l.get("role")] = roles.get(l.get("role"), 0) + 1
        P.append(
            f"| [{c['id']}]({c.get('_link', c['id'] + '.yaml')}) | {pv.get('papers', '?')} | {pv.get('tier1', '?')} | "
            f"{pv.get('tier2', '?')} | {pv.get('sweep_hits', '?')} | {roles.get('defines', 0)} | "
            f"{roles.get('extends', 0)} | {roles.get('canonical-use', 0)} | "
            f"{roles.get('routine-use', 0)} | {roles.get('critiques', 0)} |")
    with open(os.path.join(BOOK_DIR, "PREVALENCE.md"), "w") as f:
        f.write("\n".join(P) + "\n")

    # ── PRIMITIVES.md ───────────────────────────────────────────────────────
    unexposed = [c for c in ranked if (c.get("pypsa_primitive") or {}) and
                 str((c.get("pypsa_primitive") or {}).get("exposed_by", "")).strip().startswith("neither")]
    R = [
        "# One wrapper away — PyPSA primitives no workflow exposes",
        "",
        "GENERATED by `_qa/generate_index.py` — do not edit.",
        "",
        "Methods where PyPSA the LIBRARY already implements the hard part but neither",
        "pypsa-eur nor pypsa-earth reaches it from config. This is the book's most",
        "actionable output and it is a roadmap, not an index: each row is a capability that",
        "is a driver script or a config hook away, rather than a formulation project.",
        "",
        "*A primitive one layer down turns L5-from-scratch into L5-with-a-handle — the",
        "difference between a week and a quarter.*",
        "",
    ]
    if not unexposed:
        R.append("No method currently records an unexposed primitive.")
    for c in unexposed:
        prim = c["pypsa_primitive"]
        R += [f"## {c['title']}", "",
              f"- **card**: [{c['id']}]({c.get('_link', c['id'] + '.yaml')}) "
              f"({c.get('prevalence', {}).get('papers', '?')} papers)",
              f"- **primitive**: `{prim.get('symbol')}` (pypsa {prim.get('pypsa_version')})",
              f"- **exposed by**: {str(prim.get('exposed_by','')).strip()}",
              f"- **reachable via**: {str(prim.get('reachable_via','')).strip()}", ""]
    with open(os.path.join(BOOK_DIR, "PRIMITIVES.md"), "w") as f:
        f.write("\n".join(R) + "\n")

    print(f"INDEX.md: {len(cards)} cards across "
          f"{len({c.get('family') for c in cards.values()})} families"
          + (f", {len(unindexed)} UNINDEXED" if unindexed else ""))
    print(f"PREVALENCE.md: ranked {len(ranked)} methods")
    print(f"PRIMITIVES.md: {len(unexposed)} methods with an unexposed pypsa primitive")


if __name__ == "__main__":
    main()
