# -*- coding: utf-8 -*-
"""
Pass 0 of the methods book pipeline: inventory the paper corpus.

Extracts text from every PDF in papers/ exactly once (pdftotext, cached under
_qa/text/), then screens each paper against the regex bank in _qa/SLUGS.yaml.

Outputs
  _qa/text/<stem>.txt   cached plain text (gitignored — derived from tracked PDFs)
  _qa/CORPUS.yaml       paper -> {tier, dir, stem, pages, words}; the roster
                        check_methods.py validates every literature[].paper against
  _qa/SWEEP.csv         paper,tier,slug,hits — screening hints for pass 1 and the
                        auditable basis for each card's prevalence.sweep_hits

The sweep is a SCREEN, not a finding. It over-counts passing mentions and misses
methods described without their keyword; pass 1 (a read of each paper) is what
decides the paper->method mapping. Keeping the screen reproducible is the point:
a prevalence number in a card can be re-derived instead of trusted.

Usage:  python cookbooks/methods/_qa/sweep_corpus.py [--force] [--min-hits N]
"""

import argparse
import csv
import os
import re
import subprocess
import sys

import yaml

QA_DIR = os.path.dirname(os.path.abspath(__file__))
BOOK_DIR = os.path.dirname(QA_DIR)                                  # cookbooks/methods
ZYGON_DIR = os.path.dirname(os.path.dirname(BOOK_DIR))              # repo root
PAPERS_DIR = os.path.join(ZYGON_DIR, "papers")
TEXT_DIR = os.path.join(QA_DIR, "text")

# papers/<dir> -> tier number. The tier is a property of the directory, so a card
# that says tier: 1 for a tier-2 paper is a mechanical error, not a judgement call.
TIER_DIRS = {"tier1_core_group": 1, "tier2_ecosystem_community": 2}

MIN_HITS_DEFAULT = 3


def load_slugs():
    with open(os.path.join(QA_DIR, "SLUGS.yaml")) as f:
        doc = yaml.safe_load(f)
    bank = []
    for m in doc["methods"]:
        bank.append((m["id"], re.compile(m["sweep_regex"], re.IGNORECASE)))
    return doc, bank


def pdf_paths():
    out = []
    for d, tier in sorted(TIER_DIRS.items(), key=lambda kv: kv[1]):
        full = os.path.join(PAPERS_DIR, d)
        if not os.path.isdir(full):
            print(f"WARNING: {d}/ missing under papers/", file=sys.stderr)
            continue
        for fname in sorted(os.listdir(full)):
            if fname.lower().endswith(".pdf"):
                out.append((os.path.join(full, fname), fname, d, tier))
    return out


def extract(pdf, stem, force=False):
    """pdftotext once per PDF, cached. Returns the text, or None on failure."""
    txt = os.path.join(TEXT_DIR, stem + ".txt")
    if not force and os.path.isfile(txt) and os.path.getmtime(txt) >= os.path.getmtime(pdf):
        with open(txt, errors="replace") as f:
            return f.read()
    try:
        res = subprocess.run(
            ["pdftotext", "-q", pdf, "-"], capture_output=True, timeout=180, check=False
        )
    except (OSError, subprocess.TimeoutExpired) as e:
        print(f"WARNING: pdftotext failed on {stem}: {e}", file=sys.stderr)
        return None
    text = res.stdout.decode("utf8", errors="ignore")
    if not text.strip():
        print(f"WARNING: no extractable text in {stem} (scanned image?)", file=sys.stderr)
        return None
    # write unnormalised: pass-1 agents read this and want paragraphs/sections intact
    with open(txt, "w") as f:
        f.write(text)
    return text


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--force", action="store_true", help="re-extract even if cached")
    ap.add_argument("--min-hits", type=int, default=MIN_HITS_DEFAULT,
                    help=f"regex hits to count as a screening hint (default {MIN_HITS_DEFAULT})")
    args = ap.parse_args()

    os.makedirs(TEXT_DIR, exist_ok=True)
    slugdoc, bank = load_slugs()
    pdfs = pdf_paths()
    if not pdfs:
        print("no PDFs found under papers/", file=sys.stderr)
        sys.exit(1)

    corpus, rows, failed = {}, [], []
    for pdf, fname, d, tier in pdfs:
        stem = os.path.splitext(fname)[0]
        text = extract(pdf, stem, force=args.force)
        if text is None:
            failed.append(fname)
            continue
        # normalise only for matching, so regexes are not defeated by PDF line breaks
        flat = re.sub(r"\s+", " ", text)
        corpus[fname] = {
            "tier": tier,
            "dir": d,
            "stem": stem,
            "words": len(flat.split()),
        }
        for slug, rx in bank:
            n = len(rx.findall(flat))
            if n:
                rows.append({"paper": fname, "tier": tier, "slug": slug, "hits": n})

    with open(os.path.join(QA_DIR, "CORPUS.yaml"), "w") as f:
        f.write("# GENERATED by sweep_corpus.py — do not edit.\n")
        f.write("# The paper roster. check_methods.py resolves literature[].paper here,\n")
        f.write("# and enforces that a card's `tier` matches the directory the PDF is in.\n")
        yaml.safe_dump(corpus, f, sort_keys=True, default_flow_style=False, allow_unicode=True)

    rows.sort(key=lambda r: (r["slug"], -r["hits"]))
    with open(os.path.join(QA_DIR, "SWEEP.csv"), "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["paper", "tier", "slug", "hits"])
        w.writeheader()
        w.writerows(rows)

    # report: papers per slug above the hint threshold, the prevalence screen
    per_slug = {}
    for r in rows:
        if r["hits"] >= args.min_hits:
            per_slug.setdefault(r["slug"], []).append(r["paper"])
    print(f"{len(corpus)} papers extracted, {len(failed)} failed"
          + (f" ({', '.join(failed)})" if failed else ""))
    print(f"{len(rows)} paper x method hits written to SWEEP.csv\n")
    print(f"screening prevalence (>= {args.min_hits} hits):")
    order = [m["id"] for m in slugdoc["methods"]]
    for slug in sorted(order, key=lambda s: -len(per_slug.get(s, []))):
        papers = per_slug.get(slug, [])
        flag = "  <-- no hits, check the regex or the slug" if not papers else ""
        print(f"  {len(papers):3d}  {slug}{flag}")

    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
